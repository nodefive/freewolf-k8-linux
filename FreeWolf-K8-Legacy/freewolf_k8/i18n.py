def t(lang: str, key: str, **kwargs: Any) -> str:
    """Translates a key into the target language with variable formatting."""
    lang_dict = STRINGS.get(lang, STRINGS["en"])
    text = lang_dict.get(key, STRINGS["en"].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text

def get_mode_name(lang: str, mode_id: int, default_name: str) -> str:
    """Returns the localized name for a lighting mode."""
    names = MODE_NAMES.get(lang, MODE_NAMES["en"])
    return names.get(mode_id, default_name)
